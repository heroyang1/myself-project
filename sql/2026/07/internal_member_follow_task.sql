create table if not exists osh_internal_member_follow_task (
    id bigint not null auto_increment comment '主键ID',
    user_id bigint not null comment '付费用户ID',
    content varchar(2000) not null comment '跟进任务内容',
    responsible_user_id bigint not null comment '负责人用户ID',
    planned_follow_time datetime not null comment '计划跟进时间',
    remind_time datetime not null comment '提醒时间',
    status varchar(32) not null default 'pending' comment '任务状态',
    notify_channel varchar(32) not null default 'email' comment '提醒渠道',
    notify_sent tinyint(1) not null default 0 comment '是否已发送提醒',
    notify_sent_time datetime null comment '提醒发送时间',
    completed_time datetime null comment '完成时间',
    completed_by bigint null comment '完成人用户ID',
    result_note varchar(2000) null comment '完成备注',
    create_by bigint not null comment '创建人',
    create_time datetime not null default current_timestamp comment '创建时间',
    update_by bigint not null comment '更新人',
    update_time datetime not null default current_timestamp on update current_timestamp comment '更新时间',
    delete_flag tinyint(1) not null default 0 comment '删除标记',
    primary key (id),
    key idx_internal_member_follow_task_user_id (user_id),
    key idx_internal_member_follow_task_responsible_user_id (responsible_user_id),
    key idx_internal_member_follow_task_remind_scan (status, notify_sent, remind_time),
    key idx_internal_member_follow_task_planned_scan (status, planned_follow_time)
) engine=InnoDB default charset=utf8mb4 comment='内推会员跟进任务表';
