    UNIQUE KEY `uk_project_github` (`project_id`, `github_account`),
    KEY `idx_project_id` (`project_id`),
    KEY `idx_github_account` (`github_account`),
    KEY `idx_delete_flag` (`delete_flag`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='开源项目贡献人表';

